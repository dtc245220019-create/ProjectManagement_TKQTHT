#!/usr/bin/env python3
"""
Setup script for Project Management System.
Generates strong alphanumeric passwords in .env and self-signed TLS certificates.
"""
import os
import sys
import secrets
import string
from datetime import datetime, timedelta, timezone

def generate_random_password(length=24):
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))

def generate_hex_token(nbytes=32):
    return secrets.token_hex(nbytes)

def generate_tls_certificates(cert_dir="certs", days_valid=365):
    os.makedirs(cert_dir, exist_ok=True)
    cert_path = os.path.join(cert_dir, "server.crt")
    key_path = os.path.join(cert_dir, "server.key")

    if os.path.exists(cert_path) and os.path.exists(key_path):
        print(f"[+] TLS certificates already exist at {cert_dir}")
        return

    print("[*] Generating self-signed TLS certificates (RSA 3072, SHA-256)...")
    try:
        from cryptography import x509
        from cryptography.x509.oid import NameOID
        from cryptography.hazmat.primitives import hashes
        from cryptography.hazmat.primitives.asymmetric import rsa
        from cryptography.hazmat.primitives import serialization
        import ipaddress

        key = rsa.generate_private_key(
            public_exponent=65537,
            key_size=3072,
        )

        subject = issuer = x509.Name([
            x509.NameAttribute(NameOID.COUNTRY_NAME, "VN"),
            x509.NameAttribute(NameOID.STATE_OR_PROVINCE_NAME, "Thai Nguyen"),
            x509.NameAttribute(NameOID.LOCALITY_NAME, "Thai Nguyen"),
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "ICTU ATTT K23A"),
            x509.NameAttribute(NameOID.COMMON_NAME, "localhost"),
        ])

        cert = (
            x509.CertificateBuilder()
            .subject_name(subject)
            .issuer_name(issuer)
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(datetime.now(timezone.utc))
            .not_valid_after(datetime.now(timezone.utc) + timedelta(days=days_valid))
            .add_extension(
                x509.SubjectAlternativeName([
                    x509.DNSName("localhost"),
                    x509.IPAddress(ipaddress.IPv4Address("127.0.0.1")),
                ]),
                critical=False,
            )
            .sign(key, hashes.SHA256())
        )

        with open(key_path, "wb") as f:
            f.write(
                key.private_bytes(
                    encoding=serialization.Encoding.PEM,
                    format=serialization.PrivateFormat.TraditionalOpenSSL,
                    encryption_algorithm=serialization.NoEncryption(),
                )
            )

        with open(cert_path, "wb") as f:
            f.write(cert.public_bytes(serialization.Encoding.PEM))

        print(f"[+] Successfully generated server.key and server.crt in {cert_dir}")
    except Exception as e:
        print(f"[-] Failed to generate certs via cryptography: {e}")
        sys.exit(1)

